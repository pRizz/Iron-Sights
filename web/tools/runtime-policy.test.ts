import { expect, test } from 'bun:test';
import { verifyRuntimePolicy } from './runtime-policy';

const selected = [{ file: '/out/generated/web_logo.c', command: 'emcc -DGE_WEB=1' }];
const source = '/* Generated by web_logo.py; no texture/vertex payloads. */\nu32 image[4];';
test('allows a ROM-free selected source set', () => {
    expect(() => verifyRuntimePolicy(selected, source)).not.toThrow();
});
test('rejects the inherited compiled logo', () => {
    expect(() =>
        verifyRuntimePolicy(
            [...selected, { file: '/src/assets/rarewarelogo.c', command: 'emcc' }],
            source,
        ),
    ).toThrow();
});
test.each(['GE_ROMDATA_FALLBACK', 'GE_EMBED_WEAPON_ICONS'])('rejects %s', (define) => {
    expect(() =>
        verifyRuntimePolicy([{ ...selected[0], command: `emcc -D${define}=1` }], source),
    ).toThrow();
});
test('rejects missing adapters and initialized payloads', () => {
    expect(() => verifyRuntimePolicy([], source)).toThrow();
    expect(() => verifyRuntimePolicy(selected, source + '\nu32 image[4] = {1};')).toThrow();
});
