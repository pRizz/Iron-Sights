// Verify the actual selected CMake inputs before assembling a public runtime.
export function verifyRuntimePolicy(commands: unknown, logo: string): void {
    if (!Array.isArray(commands) || !commands.length)
        throw new Error('Missing CMake compile audit');
    let logoSelected = false;
    for (const entry of commands) {
        if (!entry || typeof entry.file !== 'string' || typeof entry.command !== 'string')
            throw new Error('Invalid CMake compile audit');
        const file = entry.file.replaceAll('\\', '/');
        if (file.endsWith('/assets/rarewarelogo.c'))
            throw new Error('The web build contains compiled logo payloads');
        if (file.endsWith('/generated/web_logo.c')) logoSelected = true;
        if (/-D(?:GE_ROMDATA_FALLBACK|GE_EMBED_WEAPON_ICONS)(?:\b|=)/.test(entry.command))
            throw new Error('The web build enables compiled ROM assets');
    }
    if (!logoSelected) throw new Error('The ROM-backed logo adapter was not compiled');
    if (!logo.startsWith('/* Generated by web_logo.py; no texture/vertex payloads. */'))
        throw new Error('Unknown generated logo source');
    if (/^(?:u8|u32|Vtx)\s+\w+\[[^\]]*\]\s*=/m.test(logo))
        throw new Error('The generated logo still initializes ROM payloads');
}
