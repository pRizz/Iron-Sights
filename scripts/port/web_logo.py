"""Generate ROM-free logo backing arrays, retaining typed display-list code."""
import argparse
from dataclasses import dataclass
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
DECLARATION = re.compile(r'^(u8|u32|Vtx|Gfx)\s+(\w+)\[(\d*)\]\s*=\s*\{(.*?)\};', re.M | re.S)


@dataclass(frozen=True)
class Block:
    name: str
    kind: str
    offset: int
    count: int
    size: int


def offset_of(name):
    for pattern in (r'rgba([0-9A-Fa-f]+)$', r'verts([0-9A-Fa-f]+)$',
                    r'.*_0x([0-9A-Fa-f]+)$', r'D_02([0-9A-Fa-f]{6})$'):
        match = re.fullmatch(pattern, name)
        if match:
            return int(match[1], 16)
    raise ValueError('Unknown ROM logo symbol: ' + name)


def generate(source):
    blocks = []

    def replace(match):
        kind, name, dimension, body = match.groups()
        if kind == 'Gfx':
            return match[0]
        body = re.sub(r'/\*.*?\*/|//[^\n]*', '', body, flags=re.S)
        if kind == 'Vtx':
            rows = re.findall(r'\{([^{}]+)\}', body)
            if not rows or any(len(row.split(',')) != 10 for row in rows):
                raise ValueError('Unknown vertex initializer: ' + name)
            count = len(rows)
        else:
            values = [part.strip() for part in body.split(',') if part.strip()]
            if not values or any(not re.fullmatch(r'0x[0-9A-Fa-f]+|\d+', part) for part in values):
                raise ValueError('Unknown scalar initializer: ' + name)
            count = len(values)
        if dimension and int(dimension) != count:
            raise ValueError('Mismatched array dimension: ' + name)
        width = {'u8': 1, 'u32': 4, 'Vtx': 16}[kind]
        block = Block(name, kind, offset_of(name), count, count * width)
        blocks.append(block)
        return f'{kind} {name}[{count}]; /* Populated from the player ROM. */'

    output = DECLARATION.sub(replace, source)
    if any(not declaration.startswith('Gfx ') for declaration in
           re.findall(r'^\w+\s+\w+\[[^\]]*\]\s*=', output, flags=re.M)):
        raise ValueError('Unrecognized initialized logo array remains')
    if {kind: sum(block.kind == kind for block in blocks) for kind in ('u8', 'u32', 'Vtx')} != {
            'u8': 6, 'u32': 6, 'Vtx': 26}:
        raise ValueError('Logo declarations changed; audit the ROM-free generator')
    previous_end = 0
    for block in sorted(blocks, key=lambda item: item.offset):
        if block.offset < previous_end or block.offset + block.size > 0x67F0:
            raise ValueError('Overlapping/out-of-range logo block: ' + block.name)
        previous_end = block.offset + block.size
    output = '/* Generated by web_logo.py; no texture/vertex payloads. */\n' + output
    output += '\n#include "logo.h"\nconst struct port_web_logo_block portWebLogoBlocks[] = {\n'
    for block in blocks:
        kind = {'u8': 'PORT_LOGO_BYTES', 'u32': 'PORT_LOGO_WORDS', 'Vtx': 'PORT_LOGO_VERTICES'}[block.kind]
        output += f'    {{{block.name}, sizeof({block.name}), 0x{block.offset:X}, {kind}}},\n'
    output += '};\nconst u32 portWebLogoBlockCount = sizeof(portWebLogoBlocks) / sizeof(portWebLogoBlocks[0]);\n'
    return output, blocks


def audit_wasm_payloads(source, wasm):
    """Check substantial original texture/vertex sequences are absent in Wasm.

    This supplements source-selection/BSS checks; tiny color constants are
    deliberately excluded because they also occur in ordinary program code.
    """
    checked = 0
    for match in DECLARATION.finditer(source):
        kind, name, _, body = match.groups()
        if kind not in ('u32', 'Vtx'):
            continue
        body = re.sub(r'/\*.*?\*/|//[^\n]*', '', body, flags=re.S)
        values = [int(part, 0) for part in re.findall(r'0x[0-9A-Fa-f]+|\b\d+\b', body)]
        for endian in ('little', 'big'):
            raw = b''.join(value.to_bytes(4 if kind == 'u32' else 2 if index % 10 < 6 else 1, endian)
                           for index, value in enumerate(values))
            candidates = (raw[at:at+64] for at in range(0, len(raw)-63, 4))
            signature = max(candidates, key=lambda data: sum(byte != 0 for byte in data))
            if signature in wasm:
                raise ValueError('Compiled ROM payload remains in Wasm: ' + name + ' (' + endian + ')')
        checked += 1
    return checked


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--audit-wasm', type=Path)
    options = parser.parse_args()
    if not options.output and not options.audit_wasm:
        parser.error('Choose --output and/or --audit-wasm')
    source = (ROOT / 'assets/rarewarelogo.c').read_text(encoding='utf-8')
    output, blocks = generate(source)
    if options.output:
        options.output.parent.mkdir(parents=True, exist_ok=True)
        if not options.output.exists() or options.output.read_text(encoding='utf-8') != output:
            options.output.write_text(output, encoding='utf-8', newline='\n')
        print(f'ROM-free logo: {len(blocks)} backing arrays, {sum(block.size for block in blocks)} payload bytes removed')
    if options.audit_wasm:
        checked = audit_wasm_payloads(source, options.audit_wasm.read_bytes())
        print(f'Wasm excludes original payload signatures for all {checked} texture/vertex arrays (both byte orders)')


if __name__ == '__main__':
    main()
