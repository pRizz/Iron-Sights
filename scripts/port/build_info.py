"""Stamp one build identity into the executable and its release manifest."""
import argparse
import datetime as dt
import json
import os
from pathlib import Path
import re
import subprocess

REPOSITORY = "pRizz/Project-Midas-ADS"


def metadata(root, env):
    def git(*args):
        try:
            return subprocess.check_output(["git", "-c", "safe.directory="+str(root.resolve()), "-C", str(root), *args],
                                           stderr=subprocess.DEVNULL, text=True).strip()
        except (OSError, subprocess.CalledProcessError):
            return ""
    sha = git("rev-parse", "HEAD")
    if not re.fullmatch(r"[0-9a-f]{40}", sha):
        sha = "nogit"
    branch = git("branch", "--show-current") or env.get("GITHUB_REF_NAME", "")
    count = git("rev-list", "--count", "HEAD") if git("rev-parse", "--is-shallow-repository") == "false" else "0"
    dirty = bool(git("status", "--porcelain", "--untracked-files=normal"))
    repo = env.get("GITHUB_REPOSITORY", REPOSITORY)
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repo):
        repo = REPOSITORY
    base = "https://github.com/"+repo
    ci = env.get("GITHUB_ACTIONS") == "true" and env.get("GITHUB_SHA") == sha and not dirty
    run = env.get("GITHUB_RUN_ID", "")
    tag = env.get("MIDAS_RELEASE_TAG", "")
    stamp = env.get("MIDAS_BUILD_TIME_UTC")
    if stamp:
        when = dt.datetime.strptime(stamp, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=dt.timezone.utc)
    elif env.get("SOURCE_DATE_EPOCH"):
        when = dt.datetime.fromtimestamp(int(env["SOURCE_DATE_EPOCH"]), dt.timezone.utc)
    else:
        when = dt.datetime.now(dt.timezone.utc)
    return dict(schema=1, project="Project Midas ADS", repository=repo,
                commit=sha, branch=branch, dirty=dirty, ci=ci,
                build_number=int(count or 0), build_date=when.strftime("%Y%m%d"),
                built_at=when.strftime("%Y-%m-%dT%H:%M:%SZ"),
                source_url=base+"/commit/"+sha if sha != "nogit" else "",
                workflow_url=base+"/actions/runs/"+run if ci and run.isdigit() else "",
                release_url=base+"/releases/tag/"+tag if ci and re.fullmatch(r"[A-Za-z0-9_.-]+", tag) else "",
                downloads_url=base+"/releases", builder="GitHub Actions" if ci else "Local build")


def write(root, output, env):
    info = metadata(root, env)
    fields = {"NUMBER": info["build_number"], "DATE": info["build_date"],
              "STRING": f'{info["build_number"]}-{info["build_date"]}',
              "COMMIT": info["commit"][:9], "SHA": info["commit"], "BRANCH": info["branch"],
              "TIME": info["built_at"], "DIRTY": int(info["dirty"]), "CI": int(info["ci"]),
              "SOURCE_URL": info["source_url"], "RUN_URL": info["workflow_url"],
              "RELEASE_URL": info["release_url"], "DOWNLOADS_URL": info["downloads_url"]}
    text = "/* Generated by scripts/port/build_info.py. */\n#ifndef PORT_BUILDINFO_H\n#define PORT_BUILDINFO_H\n"
    text += "".join(f"#define PORT_BUILD_{key} {json.dumps(value, ensure_ascii=True)}\n" for key, value in fields.items())
    text += "#endif\n"
    output.parent.mkdir(parents=True, exist_ok=True)
    for path, content in ((output, text), (output.parent/"build-info.json", json.dumps(info, indent=2)+"\n")):
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    write(args.root, args.output, os.environ)
