#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/../.."
cc=${CC:-gcc}
test_bin=$(mktemp /tmp/midas-abi-probe.XXXXXX)
trap 'rm -f "$test_bin" "$test_bin.exe"' EXIT

# The definitions are CMakeLists.txt's add_compile_definitions for every build,
# so the layouts asserted are the game build's.
probe_build() { # OUTPUT FLAGS...: compile and link the probe with $cc
    local output=$1; shift
    "$cc" "$@" -std=gnu11 -fms-extensions -fcommon -ffreestanding -funsigned-char -Werror=implicit-function-declaration \
        -DVERSION_US -DLANG_US -DREFRESH_NTSC -DLEFTOVERDEBUG -DLEFTOVERSPECTRUM -DBUGFIX_R0 \
        -DNONMATCHING -DAVOID_UB -D_LANGUAGE_C \
        -I. -Iinclude -Iinclude/ultra64 -Iinclude/PR -Isrc -Isrc/game -Iport/include -I"$extracted_dir" \
        scripts/port/abi_probe/probe.c -o "$output"
}
build_and_run() {
    probe_build "$test_bin" "$@" || return
    "$test_bin"
}

# The probe marks gait run names no code reads (GAIT_UNREAD): at 64 bits
# they no longer overlay their Model field, so a new reader must take
# gait_model_storage's field there and be marked BRANCHED instead. This search
# finds a member access written `->name` or `.name` on one line, spaces allowed
# after the operator. It does not catch an access split across lines, a name
# built by a macro (token pasting) or reached by raw offset, and for BRANCHED
# names it checks only that a reader exists, not that every reader takes the
# 64-bit field; those are left to review.
probe=scripts/port/abi_probe/probe.c
gait_names() { # KIND: the names of the GAIT_RUN lines of that kind
    sed -nE "s/^GAIT_RUN\(([A-Za-z0-9_]+), *[A-Za-z0-9_]+, *GAIT_$1\);[[:space:]]*$/\1/p" "$probe"
}
gait_readers() { # NAME...: member accesses to any of them in src and port/src
    local pattern status=0
    pattern=$(printf '%s\n' "$@" | paste -sd'|' -)
    grep -rnE --include='*.c' --include='*.cpp' --include='*.h' -e "(->|\.)[[:space:]]*($pattern)\b" src port/src || status=$?
    [[ $status -le 1 ]] || { echo "ABI probe: the gait run reader search failed (grep status $status)" >&2; exit 1; }
}
declared=$(sed -nE 's/^#define GAIT_RUN_NAMES ([0-9]+)$/\1/p' "$probe")
lines=$(grep -c '^GAIT_RUN(' "$probe")
same=$(gait_names SAME); branched=$(gait_names BRANCHED); unread=$(gait_names UNREAD)
parsed=$(printf '%s\n' $same $branched $unread | grep -c .)
if [[ -z $declared || $lines != "$declared" || $parsed != "$declared" ]]; then
    echo "ABI probe: GAIT_RUN_NAMES is '${declared}', the probe has $lines GAIT_RUN lines and $parsed parsed" >&2
    exit 1
fi
readers=$(gait_readers $unread)
if [[ -n $readers ]]; then
    echo "ABI probe: gait run names marked GAIT_UNREAD are read:" >&2
    echo "$readers" >&2
    exit 1
fi
for name in $branched; do
    readers=$(gait_readers "$name")
    [[ -n $readers ]] || { echo "ABI probe: gait run name $name is marked GAIT_BRANCHED but nothing reads it" >&2; exit 1; }
done

# Records some sites read through a type declared in a .c file: gunfire.c's
# ModelHeader and ModelHead (Model's first nine members), bg.c's
# HitThingSub (HitThing's), snd.c's ALSndpEvent (an ALEvent) and D_800243E4_s
# (an ALEventQueue's head) and audi.c's DMABuffer (a list link first); and
# types only ever reached through a pointer to another record (probe_views.h):
# bg.c's GlobalVisCommand and bg_envdata_entry_local (the bg file's command
# words), model.c's ModelGroupMtxBuildArg and model_audit.c's auditnode (a
# ModelNode) and front.c's BriefingData (the briefing file). The probe compares
# those declarations, copied here into a generated header, with the header
# types (probe_overlays.h and probe_views.h). The
# sources can be pointed at edited copies to see the check fail.
gunfire_c=${ABI_PROBE_GUNFIRE_C:-src/game/gunfire.c}
bg_c=${ABI_PROBE_BG_C:-src/game/bg.c}
snd_c=${ABI_PROBE_SND_C:-src/snd.c}
audi_c=${ABI_PROBE_AUDI_C:-src/audi.c}
model_c=${ABI_PROBE_MODEL_C:-src/game/model.c}
model_audit_c=${ABI_PROBE_MODEL_AUDIT_C:-port/src/model_audit.c}
front_c=${ABI_PROBE_FRONT_C:-src/game/front.c}
extracted_dir=build/abi_probe
extracted=$extracted_dir/probe_extracted.h
extract_block() { # FILE FIRST-LINE-PATTERN LAST-LINE-PATTERN NAME: the lines from first to last
    local block
    block=$(awk -v first="$2" -v last="$3" '$0 ~ first { on = 1 } on { print } on && $0 ~ last { exit }' "$1")
    # Empty, unterminated (it ran to the end of the file) or without two members: not the declaration.
    if [[ -z $block ]] || ! tail -n 1 <<<"$block" | grep -qE "$3" || [[ $(grep -c ';' <<<"$block") -lt 3 ]]; then
        echo "ABI probe: no complete $4 declaration found in $1" >&2
        exit 1
    fi
    printf '%s\n' "$block"
}
mkdir -p "$extracted_dir"
{
    echo "/* Generated by scripts/port/test_abi_probe.sh from $gunfire_c, $bg_c, $snd_c, $audi_c, $model_c, $model_audit_c and $front_c. */"
    extract_block "$gunfire_c" '^typedef struct ModelHeader [{]' '^[}] ModelHeader;' ModelHeader
    extract_block "$gunfire_c" '^typedef struct ModelHead [{]' '^[}] ModelHead;' ModelHead
    extract_block "$bg_c" '^struct HitThingSub [{]' '^[}];' HitThingSub
    extract_block "$snd_c" '^typedef union ALSndpEvent_u [{]' '^[}] ALSndpEvent;' ALSndpEvent
    extract_block "$snd_c" '^struct D_800243E4_s [{]' '^[}];' D_800243E4_s
    extract_block "$audi_c" '^typedef struct DMABuffer_s [{]' '^[}] DMABuffer;' DMABuffer
    extract_block "$bg_c" '^typedef struct GlobalVisCommand [{]' '^[}] GlobalVisCommand;' GlobalVisCommand
    extract_block "$bg_c" '^    typedef struct bg_envdata_entry_local [{]' '^    [}] bg_envdata_entry_local;' bg_envdata_entry_local
    extract_block "$model_c" '^typedef struct ModelGroupMtxBuildArg [{]' '^[}] ModelGroupMtxBuildArg;' ModelGroupMtxBuildArg
    extract_block "$model_audit_c" '^struct auditnode [{]' '^[}];' auditnode
    extract_block "$front_c" '^struct BriefingDataSomething$' '^[}];' BriefingDataSomething
    extract_block "$front_c" '^struct BriefingData$' '^[}];' BriefingData
} > "$extracted.tmp"
mv "$extracted.tmp" "$extracted"

# Some assertions only one width can break: a 64-bit layout's padding hides a
# member added after ModelHead's scale (gunfire.c), and probe.c has branches
# for each width. The widths are harness_widths.sh's, as in the other
# harnesses: on an x86 host a compiler that rejects -m32 stops the test there
# (install gcc-multilib, or set MIDAS_HARNESS_WIDTHS=64), and CI's tests job
# runs both halves. A host that cannot build a width at all (aarch64 has no
# -m32) says which half did not run, rather than passing quietly.
source scripts/port/harness_widths.sh
# On its own line, so a failure of harness_widths stops the test (set -e).
widths=$(harness_widths)
for width in $widths; do
    build_and_run $(harness_flags "$width" -msse2 -mfpmath=sse)
done
if [[ $widths != *64* ]]; then
    echo "ABI probe: the 64-bit half did not run: $cc does not build 64-bit programs by default. Not" \
        "checked: every assertion at the 64-bit layout, including probe.c's IS_64_BIT branches. CI runs" \
        "both halves."
fi
if [[ $widths != *32* ]]; then
    echo "ABI probe: the 32-bit half did not run: $cc rejects -m32 on this host. Not checked: every" \
        "assertion at the 32-bit layout, including those only it can break (probe.c's !IS_64_BIT" \
        "branches, and the .c records whose difference 64-bit padding hides, such as gunfire.c's" \
        "ModelHead with a member added after scale). CI runs both halves."
fi

# The Windows x64 layout (WIN64-001): the x86_64 MinGW compiler compiles and links
# the probe, so every _Static_assert in it holds under the Windows ABI (32-bit long,
# MinGW's default -mms-bitfields). The executable needs Windows to run, so the
# probe's run-time checks are not run here; a Windows host can run the .exe.
mingw_cc=${MINGW64_CC:-x86_64-w64-mingw32-gcc}
if command -v "$mingw_cc" >/dev/null 2>&1; then
    cc=$mingw_cc probe_build "$test_bin.exe"
    echo "ABI probe OK (Windows x64, MinGW: static assertions only; the run-time checks need Windows)"
else
    echo "ABI probe: the Windows x64 half did not run: $mingw_cc is not installed. Not checked: every" \
        "assertion at the Windows x64 layout. CI runs it."
fi
